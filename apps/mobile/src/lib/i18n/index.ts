const DICTS: Record<Language, Record<string, string>> = { pt, en, fr };

export type I18nKey = keyof typeof pt;
export type I18nVars = Record<string, string | number>;

export const LANGUAGES: { id: Language; label: string; flag: string }[] = [
  { id: 'pt', label: 'Português', flag: '🇵🇹' },
  { id: 'en', label: 'English', flag: '🇬🇧' },
  { id: 'fr', label: 'Français', flag: '🇫🇷' },
];

let currentLang: Language = 'pt';

export function setLanguage(lang: Language) {
  currentLang = lang;
}

export function getLanguage(): Language {
  return currentLang;
}

/**
 * Traduz uma chave para o idioma atual. Usa {var} para interpolação:
 * t('game.match', { n: 5 }) → "Partida #5"
 */
export function t(key: I18nKey, vars?: I18nVars): string {
  const dict = DICTS[currentLang] ?? pt;
  let str = dict[key] ?? pt[key] ?? (key as string);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
